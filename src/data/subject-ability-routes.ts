/** 把优势入口转成一次可执行、可核对、可记录的小实验。 */
export function buildObservableTrialSteps(subject: SubjectName, dimension: Dimension): readonly string[] {
  return [
    `准备：选一小段${subject}内容或一道代表题`,
    `执行：先按上面的${dimensionActionLabels[dimension]}动作处理一遍`,
    `核对：${subjectCheckActions[subject]}`,
    '记录：写下这样做是否更容易开始、少漏信息或更快发现错误',
  ]
}

